import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const cssPath = join(root, "app", "globals.css");
const outPath = join(root, "lib", "a11y", "design-tokens.ts");

const css = readFileSync(cssPath, "utf8");
const rootMatch = css.match(/:root\s*\{([^}]+)\}/);

if (!rootMatch) {
  console.error("Could not find :root block in globals.css");
  process.exit(1);
}

const variables = {};
for (const line of rootMatch[1].split("\n")) {
  const match = line.match(/^\s*--([a-z0-9-]+):\s*(#[0-9a-fA-F]{3,8});/);
  if (match) {
    variables[match[1]] = match[2].toLowerCase();
  }
}

const semanticNames = [
  "background",
  "foreground",
  "card",
  "card-foreground",
  "primary",
  "primary-foreground",
  "secondary",
  "secondary-foreground",
  "muted",
  "muted-foreground",
  "accent",
  "accent-foreground",
  "destructive",
  "destructive-foreground",
  "border",
  "input",
  "ring",
];

/** @type {Record<string, string>} */
const tokenMap = {};

for (const name of semanticNames) {
  const hex = variables[name];
  if (!hex) continue;
  tokenMap[`text-${name}`] = hex;
  tokenMap[`bg-${name}`] = hex;
}

const entries = Object.entries(tokenMap)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([key, value]) => `  "${key}": "${value}",`)
  .join("\n");

const output = `/** Semantic design token colors from app/globals.css :root (light theme). */
/** Generated by scripts/generate-design-tokens.mjs — do not edit manually. */
export const DESIGN_TOKEN_COLORS: Record<string, string> = {
${entries}
};

const TEXT_TOKEN_PREFIX = "text-";
const BG_TOKEN_PREFIX = "bg-";

/** Returns the first resolvable text-* token class and its hex color. */
export function findTextTokenColor(
  classTokens: string[],
): { tokenClass: string; hex: string } | null {
  for (const token of classTokens) {
    if (!token.startsWith(TEXT_TOKEN_PREFIX)) continue;
    const hex = DESIGN_TOKEN_COLORS[token];
    if (hex) return { tokenClass: token, hex };
  }
  return null;
}

/** Returns the first resolvable bg-* token class and its hex color. */
export function findBackgroundTokenColor(
  classTokens: string[],
): { tokenClass: string; hex: string } | null {
  for (const token of classTokens) {
    if (!token.startsWith(BG_TOKEN_PREFIX)) continue;
    const hex = DESIGN_TOKEN_COLORS[token];
    if (hex) return { tokenClass: token, hex };
  }
  return null;
}
`;

writeFileSync(outPath, output, "utf8");
console.log(`Wrote ${Object.keys(tokenMap).length} tokens to lib/a11y/design-tokens.ts`);
